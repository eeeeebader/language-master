import type { StoryDocument, StoryToken } from "@lm/schema";

type Tok = [text: string, lemma: string, pos: StoryToken["pos"], gloss?: string];

/** Build sentence tokens from a compact tuple list; punctuation attaches to the previous token. */
function s(
  id: string,
  translation: string,
  toks: Tok[],
): StoryDocument["paragraphs"][number][number] {
  return {
    id,
    translation,
    tokens: toks.map(([text, lemma, pos, gloss], i) => {
      const next = toks[i + 1];
      const nextIsPunct = next ? /^[.,;:!?]$/.test(next[0]) : false;
      const isOpening = /^[¿¡]$/.test(text);
      return {
        text,
        lemma,
        pos,
        gloss,
        ws: nextIsPunct || isOpening || i === toks.length - 1 ? "" : " ",
        isWord: !/^[¿¡.,;:!?]$/.test(text),
      };
    }),
  };
}

const P = (t: string): Tok => [t, t, "other"];

